/**
 * Writes the bundled synthetic clip with ffmpeg lavfi sources.
 * testsrc2 draws the pattern. sine is quiet for the first 5s and louder after,
 * so the loudest-15s proxy lands at 5–20s. No stock or copyrighted media.
 */
import { spawn } from 'node:child_process'
import { mkdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import {
  CAPTIONS_SRT,
  LOUD_AMPLITUDE,
  QUIET_AMPLITUDE,
  QUIET_SECONDS,
  SAMPLE_DURATION,
  SAMPLE_FPS,
  SAMPLE_HEIGHT,
  SAMPLE_WIDTH,
} from '../src/domain/sample.ts'

const appRoot = path.resolve(import.meta.dirname, '..')
const outDir = path.join(appRoot, 'public', 'sample')
mkdirSync(outDir, { recursive: true })

const video = path.join(outDir, 'pattern.mp4')
const volume = `volume='if(lt(t,${QUIET_SECONDS}),${QUIET_AMPLITUDE},${LOUD_AMPLITUDE})':eval=frame`
const args = [
  '-y',
  '-f',
  'lavfi',
  '-i',
  `testsrc2=size=${SAMPLE_WIDTH}x${SAMPLE_HEIGHT}:rate=${SAMPLE_FPS}:duration=${SAMPLE_DURATION}`,
  '-f',
  'lavfi',
  '-i',
  `sine=frequency=440:sample_rate=48000:duration=${SAMPLE_DURATION}`,
  '-filter_complex',
  `[1:a]${volume}[a]`,
  '-map',
  '0:v:0',
  '-map',
  '[a]',
  '-c:v',
  'libx264',
  '-preset',
  'veryfast',
  '-crf',
  '32',
  '-pix_fmt',
  'yuv420p',
  '-c:a',
  'aac',
  '-b:a',
  '64k',
  '-movflags',
  '+faststart',
  '-t',
  String(SAMPLE_DURATION),
  video,
]

const child = spawn('ffmpeg', args, { shell: false })
let stderr = ''
child.stderr.setEncoding('utf8')
child.stderr.on('data', (chunk: string) => {
  stderr += chunk
})
const code: number = await new Promise((resolve) => {
  child.on('close', (status) => resolve(status ?? 1))
})
if (code !== 0) {
  process.stderr.write(stderr)
  process.exit(code)
}

writeFileSync(path.join(outDir, 'captions.srt'), CAPTIONS_SRT)
writeFileSync(
  path.join(outDir, 'SOURCE.txt'),
  [
    'Synthetic test pattern for the cut room.',
    'Generated by scripts/generate-sample.ts with ffmpeg lavfi sources only.',
    `Video: testsrc2 ${SAMPLE_WIDTH}x${SAMPLE_HEIGHT} at ${SAMPLE_FPS} fps, ${SAMPLE_DURATION}s.`,
    `Audio: sine 440 Hz. Amplitude ${QUIET_AMPLITUDE} for the first ${QUIET_SECONDS}s, then ${LOUD_AMPLITUDE}.`,
    'The loudest-15s proxy therefore starts at 5s. This is not a recording, not stock footage, and not an upstream demo clip.',
    'Captions in captions.srt are timed text written by the same script.',
    '',
  ].join('\n'),
)
process.stdout.write(`wrote ${video}\n`)
