"""Record fallback fixtures by running the Nautilus sidecar on synthetic bars.

This script is a one-shot recorder. The app replays the JSON it writes when
Python or nautilus_trader is missing. It is not a TypeScript engine and it
does not reimplement NautilusTrader.

Requires the nautilus_trader package. Sample bars are original synthetic data
(CC0-1.0), not exchange history and not upstream sample files.
"""

from __future__ import annotations

import json
import math
import random
import sys
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sidecar"))

from backtest import run_request  # noqa: E402

FASTS = (8, 12, 20)
SLOWS = (26, 50)
TRAILS = (3.0, 5.0, 8.0)
BAR_COUNT = 180
START = datetime(2024, 1, 1, tzinfo=UTC)


def synthesize(seed: int, start_price: float) -> list[dict]:
    rng = random.Random(seed)
    price = start_price
    bars = []
    for index in range(BAR_COUNT):
        drift = 0.0012 * math.sin(index / 12.0) + 0.00035
        shock = rng.gauss(0, 0.013)
        if index % 37 == 0:
            shock += 0.03
        if index % 53 == 0:
            shock -= 0.024
        open_ = price
        close = max(50.0, open_ * (1.0 + drift + shock))
        wick = abs(rng.gauss(0, 0.006)) + 0.0015
        high = max(open_, close) * (1.0 + wick)
        low = min(open_, close) * (1.0 - wick)
        open_r = round(open_, 2)
        close_r = round(close, 2)
        high_r = round(max(high, open_r, close_r), 2)
        low_r = round(min(low, open_r, close_r), 2)
        if low_r <= 0:
            low_r = min(open_r, close_r)
        bars.append(
            {
                "time": (START + timedelta(days=index)).date().isoformat(),
                "open": open_r,
                "high": high_r,
                "low": low_r,
                "close": close_r,
                "volume": round(800 + rng.random() * 4200, 4),
            }
        )
        price = close
    return bars


def main() -> None:
    series = {
        "ETH": {
            "label": "SAMPLE-ETH",
            "seed": 20261117,
            "startPrice": 2400.0,
            "note": "Original synthetic daily bars. Not exchange data.",
        },
        "BTC": {
            "label": "SAMPLE-BTC",
            "seed": 20261118,
            "startPrice": 64000.0,
            "note": "Original synthetic daily bars. Not exchange data.",
        },
    }
    bars_out = {
        "license": "CC0-1.0",
        "source": (
            "Original synthetic OHLC generated by scripts/record_sample_fixtures.py "
            "for this demo. Not copied from an exchange, a data vendor, or "
            "NautilusTrader's sample files."
        ),
        "series": {},
    }
    runs: dict[str, dict] = {}
    engine_name = ""
    for symbol, meta in series.items():
        bars = synthesize(meta["seed"], meta["startPrice"])
        bars_out["series"][symbol] = {
            "label": meta["label"],
            "note": meta["note"],
            "bars": bars,
        }
        for fast in FASTS:
            for slow in SLOWS:
                if fast >= slow:
                    continue
                for trail in TRAILS:
                    result = run_request(
                        {
                            "symbol": symbol,
                            "fast": fast,
                            "slow": slow,
                            "trailPct": trail,
                            "bars": bars,
                        }
                    )
                    engine_name = result["engine"]
                    key = f"{symbol}|{fast}|{slow}|{trail:g}"
                    runs[key] = {
                        "params": result["params"],
                        "stats": result["stats"],
                        "trades": result["trades"],
                        "equity": result["equity"],
                        "openPosition": result["openPosition"],
                    }
                    stats = result["stats"]
                    print(
                        f"{key} trades={stats['tradeCount']} "
                        f"net={stats['netReturn']} dd={stats['maxDrawdown']} "
                        f"sharpe={stats['sharpe']}",
                        file=sys.stderr,
                    )

    recorded = {
        "license": "CC0-1.0",
        "engine": engine_name,
        "nautilusLicense": "LGPL-3.0",
        "nautilusRepo": "https://github.com/nautechsystems/nautilus_trader",
        "source": (
            "Recorded by scripts/record_sample_fixtures.py, which calls the local "
            "NautilusTrader BacktestEngine through sidecar/backtest.py on the bundled "
            "synthetic bars. These fixtures are saved output. The TypeScript UI replays "
            "them when the sidecar is unavailable. It is not a reimplementation of the "
            "Rust engine."
        ),
        "assumptions": (
            "Long-only EMA cross on daily sample bars. A cross up buys about 95% of "
            "cash at the bar close via a simulated market order. A reduce-only "
            "trailing-stop-market (basis points) manages the exit, and a cross down "
            "closes the position. Venue id is SIM. Taker fee is 4 bps. Starting equity "
            "is 10000 quote units. Sharpe is the mean of daily equity changes divided "
            "by their sample standard deviation, times sqrt(365), with a risk-free rate "
            "of 0. Figures are sample research output, not live performance or advice."
        ),
        "runs": runs,
    }
    data_dir = ROOT / "src" / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    (data_dir / "sample-bars.json").write_text(json.dumps(bars_out, indent=2) + "\n")
    (data_dir / "recorded-runs.json").write_text(json.dumps(recorded, indent=2) + "\n")
    print(f"wrote {len(runs)} runs with {engine_name}", file=sys.stderr)


if __name__ == "__main__":
    main()
